def get_job_combinations(job_idx: int, max_jobs: int = 24) -> list:
    """Map job index to list of (sample_size, threshold, seed) tuples"""
    
    # Load dynamic parameters from feasibility config
    config = load_feasibility_config()
    if config is None:
        return []
    
    # Get training sizes from config (generated by script 00)
    sample_sizes = config.get('training_sizes', [1, 2, 4, 8, 16, 32, 64])
    thresholds = config.get('thresholds', [0, 0.25, 0.5, 0.75])  # 4 thresholds
    seeds = [0, 1, 2, 3, 4, 5, 6, 7]  # 8 seeds
    
    # Generate all combinations: len(sample_sizes) × 4 thresholds × 8 seeds
    all_combinations = []
    for sample_size in sample_sizes:
        for threshold in thresholds:
            for seed in seeds:
                all_combinations.append((sample_size, threshold, seed))
    
    total_combinations = len(all_combinations)
    
    # Handle case where job_idx exceeds available jobs or no combinations
    if job_idx >= max_jobs or total_combinations == 0:
        return []
    
    # Dynamic job distribution: handle any number of combinations
    configs_per_job = total_combinations // max_jobs
    remainder = total_combinations % max_jobs
    
    # Jobs 0 to (remainder-1) get one extra config to handle remainder
    if job_idx < remainder:
        start_idx = job_idx * (configs_per_job + 1)
        end_idx = start_idx + configs_per_job + 1
    else:
        start_idx = remainder * (configs_per_job + 1) + (job_idx - remainder) * configs_per_job
        end_idx = start_idx + configs_per_job
    
    # Handle case where this job has no work (total_combinations < max_jobs)
    if start_idx >= total_combinations:
        return []
    
    # Ensure we don't exceed the total combinations
    end_idx = min(end_idx, total_combinations)
    
    return all_combinations[start_idx:end_idx]


